// Rebuilds the marking keys from the model-answer PDFs in exams/reference/ (needs pdftotext, from poppler-utils):
//   node saq/tools/build-keys.mjs
// Writes saq/keys/NN_slug.txt (the text of each PDF) and saq/keys/bundle.js (index.json + the texts) for the Worker.
// The stems and titles in saq/keys/index.json are curated by hand; this script never changes them.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const keys = path.join(here, '..', 'keys');
const pdfs = path.join(here, '..', '..', 'exams', 'reference');

const index = JSON.parse(readFileSync(path.join(keys, 'index.json'), 'utf8'));
const files = readdirSync(pdfs).filter(f => f.endsWith('.pdf'));
const bundle = index.map(q => {
  const pdf = files.find(f => f === `${q.id}_${q.slug}.pdf`);
  if (!pdf) throw new Error(`No PDF for ${q.id}_${q.slug}`);
  const txt = path.join(keys, pdf.replace(/\.pdf$/, '.txt'));
  execFileSync('pdftotext', ['-layout', path.join(pdfs, pdf), txt]);
  const key = readFileSync(txt, 'utf8').replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trim();
  return { id: q.id, title: q.title, stem: q.stem, key };
});
if (files.length !== index.length) console.warn(`${files.length} PDFs but ${index.length} questions in index.json`);
writeFileSync(path.join(keys, 'bundle.js'), `// Generated by saq/tools/build-keys.mjs from exams/reference/*.pdf and keys/index.json. Do not edit.\nexport default ${JSON.stringify(bundle, null, 1)};\n`);
console.log(`saq/keys/bundle.js: ${bundle.length} questions`);
