// Rebuilds what the Worker knows about questions (needs pdftotext, from poppler-utils): npm run build-keys
// - the 10-week programme, from the Exam Prep page (../exams/index.html), each question with a stable id from its wording
// - the 29 bank questions (keys/index.json, curated by hand) and their model answers, the text of ../exams/reference/*.pdf
// - drafted keys for programme questions, keys/drafts/<id>.md, used only once their first line is "status: approved"
// A programme question whose wording matches a bank question uses that model answer.
// Writes src/bundle.js (and keys/text/, a scratch copy of the PDF text, not committed).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { readProgramme, overlap } from './programme.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const keys = path.join(root, 'keys'), text = path.join(keys, 'text'), drafts = path.join(keys, 'drafts'), pdfs = path.join(root, '..', 'exams', 'reference');
mkdirSync(text, { recursive: true });

const index = JSON.parse(readFileSync(path.join(keys, 'index.json'), 'utf8'));
const files = readdirSync(pdfs).filter(f => f.endsWith('.pdf'));
const bank = index.map(q => {
  const pdf = files.find(f => f === `${q.id}_${q.slug}.pdf`);
  if (!pdf) throw new Error(`No PDF for ${q.id}_${q.slug}`);
  const txt = path.join(text, pdf.replace(/\.pdf$/, '.txt'));
  execFileSync('pdftotext', ['-layout', path.join(pdfs, pdf), txt]);
  const key = readFileSync(txt, 'utf8').replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n').trim();
  return { id: `b${q.id}`, title: q.title, stem: q.stem, key, pdf };
});
if (files.length !== index.length) console.warn(`${files.length} PDFs but ${index.length} questions in index.json`);

const approved = {};
if (existsSync(drafts)) for (const f of readdirSync(drafts).filter(f => f.endsWith('.md'))) {
  const [first, ...rest] = readFileSync(path.join(drafts, f), 'utf8').split('\n');
  if (first.trim() === 'status: approved') approved[f.replace(/\.md$/, '')] = rest.join('\n').trim();
}

const programme = readProgramme(path.join(root, '..', 'exams', 'index.html'));
let matched = 0, drafted = 0, total = 0;
for (const w of programme.weeks) for (const s of w.sessions) for (const q of s.questions) {
  total++;
  const m = bank.find(b => overlap(`${q.stem} ${q.q}`, b.stem) >= 0.9);
  if (m) { q.key = m.key; q.keySource = m.id; matched++; }
  else if (approved[q.id]) { q.key = approved[q.id]; q.keySource = 'drafted'; drafted++; }
}

// --check: fail if src/bundle.js is out of date with the programme (wording, order, which questions have keys). The key
// texts themselves are not compared: pdftotext versions differ in whitespace.
if (process.argv.includes('--check')) {
  const strip = weeks => JSON.stringify(weeks.map(w => ({ ...w, sessions: w.sessions.map(s => ({ ...s, questions: s.questions.map(({ key, ...q }) => q) })) })));
  const { default: current } = await import(path.join(root, 'src', 'bundle.js'));
  if (strip(current.weeks) !== strip(programme.weeks) || current.bank.length !== bank.length) {
    console.error('saq/src/bundle.js is out of date with exams/index.html. Run: npm run build-keys --prefix saq, and commit it.');
    process.exit(1);
  }
  console.log('saq/src/bundle.js is up to date.');
  process.exit(0);
}

writeFileSync(path.join(root, 'src', 'bundle.js'), `// Generated by saq/tools/build-keys.mjs from exams/index.html, exams/reference/ and saq/keys/. Do not edit.\nexport default ${JSON.stringify({ blocks: programme.blocks, weeks: programme.weeks, bank }, null, 1)};\n`);
console.log(`src/bundle.js: ${total} programme questions (${matched} with a bank model answer, ${drafted} with an approved drafted key), ${bank.length} bank questions`);
