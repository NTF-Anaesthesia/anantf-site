const assert=require('node:assert/strict');
const m=require('../haemodynamics/model.js');
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} != ${expected}`);
near(m.flow(2,20,80).area,Math.PI);
near(m.flow(2,20,80).sv,Math.PI*20);
near(m.flow(2,20,80).co,Math.PI*1.6);
near(m.flow(2,10,110).co,Math.PI*1.1);
near(m.flow(2,20,80,0,10).measuredCo/m.flow(2,20,80).co,1.21);
near(m.flow(2,20,80,0,-10).measuredCo/m.flow(2,20,80).co,.81);
near(m.flow(2,20,80,60).measuredVti,10);
near(m.ejection(40,70,0).forward,28);
near(m.ejection(120,75,50).total,90);
near(m.ejection(120,75,50).forward,45);
near(m.ivc(20,10).collapse,50);
near(m.ivc(20,10).distend,100);
near(m.ivc(20,10).variability,200/3);
assert.equal(m.ivc(10,20),null);
assert.equal(m.ivc(10,0),null);
assert.ok(m.plr(40,'responsive').vtiChange>10);
assert.ok(m.plr(40,'nonresponsive').vtiChange<5);
assert.ok(m.plr(140,'responsive').vtiChange<.1);
assert.ok(m.plr(40,'tachycardia').coChange>m.plr(40,'tachycardia').vtiChange);
near(m.velocityVariation(1.12,0.88).delta,24);
near(m.velocityVariation(0.63,0.46).delta,100*0.17/0.545);
assert.equal(Math.round(m.velocityVariation(0.63,0.46).delta*10)/10,31.2);
assert.equal(m.velocityVariation(0.46,0.63),null);
console.log('23 haemodynamics numerical checks passed.');
